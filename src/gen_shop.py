def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def ins(table, cols, rows):
    out = [f"INSERT INTO {table} ({', '.join(cols)}) VALUES"]
    out.append(",\n".join("  (" + ", ".join(q(v) for v in r) + ")" for r in rows) + ";")
    return "\n".join(out) + "\n\n"


def dt(start, end):
    s = int((end - start).total_seconds())
    return (start + timedelta(seconds=random.randint(0, s))).replace(microsecond=0)


def main():
    sql = [SCHEMA]
    sql.append(ins("categories", ["id", "name", "parent_id"], CATS))

    prods = []
    for i, (name, cat, tl) in enumerate(PRODUCTS, 1):
        stock = 0 if i in (3, 12, 26, 35) else random.randint(1, 120)
        disc = 1 if i in (3, 20, 41) else 0
        added = dt(datetime(2024, 6, 1), datetime(2025, 9, 1)).strftime("%Y-%m-%d")
        prods.append((i, name, cat, tl * 100, stock, disc, added))
    sql.append(ins("products", ["id", "name", "category_id", "price_kurus", "stock", "discontinued", "added_at"], prods))

    emps = [
        (1, "Oguz", "Kural", "CEO", "Management", None, 25000000, "2019-03-01"),
        (2, "Selin", "Aydin", "Sales Director", "Sales", 1, 12000000, "2019-09-15"),
        (3, "Burak", "Celik", "Ops Director", "Operations", 1, 11500000, "2020-01-10"),
        (4, "Elif", "Demir", "Sales Manager", "Sales", 2, 8000000, "2020-06-01"),
        (5, "Kerem", "Kaya", "Sales Manager", "Sales", 2, 7800000, "2021-02-15"),
        (6, "Zeynep", "Arslan", "Sales Rep", "Sales", 4, 4500000, "2021-08-01"),
        (7, "Emre", "Sahin", "Sales Rep", "Sales", 4, 4300000, "2022-03-20"),
        (8, "Gizem", "Polat", "Sales Rep", "Sales", 5, 4600000, "2022-11-07"),
        (9, "Can", "Tekin", "Sales Rep", "Sales", 5, 4100000, "2024-01-15"),
        (10, "Derya", "Koc", "Warehouse Lead", "Operations", 3, 5200000, "2020-10-01"),
        (11, "Ufuk", "Kurt", "Warehouse Staff", "Operations", 10, 3400000, "2023-05-02"),
        (12, "Pinar", "Gunes", "Intern", "Sales", 6, 1800000, "2026-07-01"),
    ]
    sql.append(ins("employees", ["id", "first_name", "last_name", "title", "department", "manager_id",
                                 "salary_kurus", "hired_at"], emps))

    custs = []
    used_emails = set()
    N_CUST = 80
    for i in range(1, N_CUST + 1):
        fn, ln = random.choice(FIRST), random.choice(LAST)
        email = f"{fn.lower()}.{ln.lower()}{i}@{random.choice(['mail.com', 'omu.edu.tr', 'example.org'])}"
        used_emails.add(email)
        phone = None if random.random() < 0.2 else f"05{random.randint(30, 59)}{random.randint(1000000, 9999999)}"
        city = None if random.random() < 0.08 else random.choices(CITIES, CITY_W)[0]
        birth = None if random.random() < 0.15 else dt(datetime(1960, 1, 1), datetime(2007, 1, 1)).strftime("%Y-%m-%d")
        joined = dt(datetime(2024, 9, 1), datetime(2026, 9, 30)).strftime("%Y-%m-%d")
        ref = None
        if i > 5 and random.random() < 0.3:
            ref = random.randint(1, i - 1)
        custs.append([i, fn, ln, email, phone, city, birth, joined, ref])
    # make referral chains a bit deeper and deterministic for recursive-CTE exercises
    custs[9][8] = 3     # 10 <- 3
    custs[24][8] = 10   # 25 <- 10
    custs[49][8] = 25   # 50 <- 25
    custs[69][8] = 50   # 70 <- 50
    custs[2][8] = None  # 3 is a root
    # referrer must have joined before the referred customer: fix joined dates
    custs.sort(key=lambda c: c[0])
    for c in custs:
        if c[8] is not None:
            ref_join = custs[c[8] - 1][7]
            if c[7] <= ref_join:
                c[7] = (datetime.strptime(ref_join, "%Y-%m-%d") + timedelta(days=random.randint(1, 40))).strftime("%Y-%m-%d")
    sql.append(ins("customers", ["id", "first_name", "last_name", "email", "phone", "city", "birth_date",
                                 "joined_at", "referred_by"], custs))

    # ------------------------------------------------------------ orders
    never_buy = set(random.sample(range(1, N_CUST + 1), 10))
    buyers = [c for c in range(1, N_CUST + 1) if c not in never_buy]
    weights = [random.choice([1, 1, 1, 2, 3, 6]) for _ in buyers]   # some heavy buyers
    never_sold = {20, 26, 40}  # Kucuk Prens, Maus, Gift Card 500 never sold
    sellable = [p for p in prods if p[0] not in never_sold]
    reps = [6, 7, 8, 9, 4, 5]
    orders, items, pays = [], [], []
    pay_id = 0
    N_ORD = 420
    raw = []
    for _ in range(N_ORD):
        c = random.choices(buyers, weights)[0]
        joined = datetime.strptime(custs[c - 1][7], "%Y-%m-%d")
        start = max(joined, datetime(2025, 1, 1))
        if start > datetime(2026, 10, 31):
            start = datetime(2026, 10, 1)
        raw.append((dt(start, datetime(2026, 10, 31, 23, 59, 59)), c))
    raw.sort()
    for oid, (when, c) in enumerate(raw, 1):
        age_days = (datetime(2026, 11, 1) - when).days
        if age_days < 6:
            status = random.choice(["pending", "pending", "shipped"])
        elif age_days < 15:
            status = random.choice(["shipped", "delivered", "delivered"])
        else:
            status = random.choices(["delivered", "cancelled", "returned"], [86, 9, 5])[0]
        rep = None if random.random() < 0.35 else random.choice(reps)
        if rep == 9 and when < datetime(2024, 1, 15):
            rep = 6
        city = custs[c - 1][5] or random.choice(CITIES)
        if random.random() < 0.1:
            city = random.choice(CITIES)
        orders.append((oid, c, rep, when.strftime("%Y-%m-%d %H:%M:%S"), status, city))
        n = random.choices([1, 2, 3, 4, 5], [40, 30, 15, 10, 5])[0]
        total = 0
        for p in random.sample(sellable, n):
            qty = random.choices([1, 2, 3, 5], [70, 20, 7, 3])[0]
            price = p[3]
            if random.random() < 0.15:          # discounted line
                price = int(round(price * random.choice([0.8, 0.9]), -2))
            if when < datetime(2025, 7, 1) and random.random() < 0.5:   # prices rose mid-2025
                price = int(round(price * 0.85, -2))
            items.append((oid, p[0], qty, price))
            total += qty * price
        if status in ("delivered", "shipped", "returned") or (status == "pending" and random.random() < 0.4):
            method = random.choices(["card", "cash", "transfer"], [70, 10, 20])[0]
            if total > 1000000 and random.random() < 0.6:   # big orders paid in 2 installments
                first = total // 2
                pay_id += 1
                pays.append((pay_id, oid, first, method, (when + timedelta(minutes=5)).strftime("%Y-%m-%d %H:%M:%S")))
                pay_id += 1
                pays.append((pay_id, oid, total - first, method, (when + timedelta(days=30)).strftime("%Y-%m-%d %H:%M:%S")))
            else:
                pay_id += 1
                amt = total if random.random() > 0.04 else total - 5000  # a few underpaid orders
                pays.append((pay_id, oid, amt, method, (when + timedelta(minutes=random.randint(1, 600))).strftime("%Y-%m-%d %H:%M:%S")))

    sql.append(ins("orders", ["id", "customer_id", "employee_id", "ordered_at", "status", "ship_city"], orders))
    for k in range(0, len(items), 300):
        sql.append(ins("order_items", ["order_id", "product_id", "quantity", "unit_price_kurus"], items[k:k + 300]))
    sql.append(ins("payments", ["id", "order_id", "amount_kurus", "method", "paid_at"], pays))

    # ------------------------------------------------------------ reviews
    bought = {}
    odate = {o[0]: o for o in orders}
    for (oid, pid, _, _) in items:
        o = odate[oid]
        if o[4] == "delivered":
            bought.setdefault((o[1], pid), o[3])
    pairs = random.sample(sorted(bought), 150)
    revs = []
    for rid, (c, p) in enumerate(pairs, 1):
        base = datetime.strptime(bought[(c, p)], "%Y-%m-%d %H:%M:%S")
        bias = {9: 4.6, 13: 4.4, 3: 2.2, 27: 2.8, 1: 4.5}.get(p, 3.8)
        rating = max(1, min(5, round(random.gauss(bias, 1.0))))
        comment = None if random.random() < 0.35 else random.choice(COMMENTS)
        revs.append((rid, p, c, rating, comment, (base + timedelta(days=random.randint(3, 40))).strftime("%Y-%m-%d")))
    # three suspicious reviews from customers who never bought the product
    for extra in [(c, p) for c in sorted(never_buy)[:3] for p in (1,)]:
        revs.append((len(revs) + 1, extra[1], extra[0], 1, "Fake review?", "2026-05-05"))
    sql.append(ins("reviews", ["id", "product_id", "customer_id", "rating", "comment", "created_at"], revs))

    OUT.write_text("".join(sql))
    print(f"wrote {OUT}: {len(orders)} orders, {len(items)} items, {len(pays)} payments, {len(revs)} reviews")


if __name__ == "__main__":
    main()
